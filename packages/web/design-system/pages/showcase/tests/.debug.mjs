import { chromium } from "playwright";
const b = await chromium.launch(); const p = await b.newPage();
const errors = [];
p.on("pageerror", e => errors.push("pageerror: " + e.message.slice(0, 200)));
p.on("response", r => { if (r.status() >= 400) errors.push(r.status() + " " + r.url()); });
await p.goto("http://localhost:8765/papit/#/web/design-system/atoms/switch/showcase");
await p.waitForTimeout(3000);
await p.screenshot({ path: "/tmp/sc-shot.png" });
console.log(await p.evaluate(() => { const sc = document.querySelector("pap-showcase"); const r = sc.shadowRoot?.querySelector("pap-router"); return { pkgs: sc.data?.packages.length, route: sc.route?.entry?.name, page: sc.route?.page, routed: r?.shadowRoot?.innerHTML.length }; }));
console.log(errors.slice(0, 10));
await b.close();
