import { describe, it, before, after } from "node:test";
import assert from "node:assert";
import fs from "node:fs";

import { analysePackage } from "@papit/analyse";
import { generateReact, MARKER } from "@papit/react";

import { fixturePackage, tmp } from "./helpers.js";

describe("generateReact on the fixture package", () => {
    let root;
    let code;

    before(() => {
        root = tmp();
        fixturePackage(root);
        code = generateReact(analysePackage(root));
    });
    after(() => fs.rmSync(root, { recursive: true, force: true }));

    /** The source of `export function <name>(...) { ... }`. */
    const component = (name) => code.match(new RegExp(`export function ${name}\\([\\s\\S]*?\\n}`))?.[0] ?? "";
    /** The source of `export interface <name>Props ... { ... }`. */
    const props = (name) => code.match(new RegExp(`export interface ${name}Props [\\s\\S]*?\\n}`))?.[0] ?? "";
    /** The source of the `declare module "react"` block. */
    const augmentation = () => code.match(/^declare module "react" \{[\s\S]*?\n\}/m)?.[0] ?? "";

    it("starts with the \"use client\" directive, then the marker line", () => {
        assert.strictEqual(MARKER, "// generated by @papit/react");
        assert.deepStrictEqual(code.split("\n").slice(0, 2), [`"use client";`, MARKER]);
    });

    it("imports the element types by the package's own name", () => {
        assert.match(code, /^import type \{ Fixture as FixtureElement, FixtureItem as FixtureItemElement \} from "@tmp\/fixture";$/m);
    });

    // SSR: the package defines its elements on import and touches window/HTMLElement at module scope
    it("has no top-level side-effect import of the package, only a browser-only dynamic one", () => {
        assert.doesNotMatch(code, /^import\s+["']@tmp\/fixture["'];?$/m);
        assert.doesNotMatch(code, /^import\s+[^t].*from\s+["']@tmp\/fixture["']/m);
        assert.match(code, /^if \(typeof window !== "undefined"\)\n\{\n    void import\("@tmp\/fixture"\);\n\}$/m);
    });

    it("uses JSX, no createElement and no forwardRef", () => {
        assert.doesNotMatch(code, /createElement|forwardRef/);
        assert.match(component("Fixture"), /return <fixture-el [^\n]*\{\.\.\.props\} ref=\{setRef\} \/>;/);
        assert.match(component("FixtureItem"), /return <fixture-item \{\.\.\.props\} ref=\{setRef\} \/>;/);
    });

    it("exports one function component per element, named after the class, returning ReactElement", () => {
        assert.deepStrictEqual([...code.matchAll(/^export function (\w+)\(/gm)].map(m => m[1]), ["Fixture", "FixtureItem"]);
        assert.match(component("Fixture"), /^export function Fixture\(\{[^}]*\}: FixtureProps\): ReactElement \{$/m);
        assert.match(component("FixtureItem"), /^export function FixtureItem\(\{ ref, onReady, \.\.\.props \}: FixtureItemProps\): ReactElement \{$/m);
    });

    it("declares an explicit props interface over the HTML attributes, without the clashing keys", () => {
        assert.match(props("Fixture"), /^export interface FixtureProps extends Omit<HTMLAttributes<FixtureElement>, "label" \| "open" \| "variant" \| "items" \| "count" \| "tone" \| "when" \| "withClick" \| "disabled" \| "onChange" \| "onValueChange" \| "onTabSelect" \| "onReady"> \{$/m);
        assert.match(props("FixtureItem"), /^export interface FixtureItemProps extends Omit<HTMLAttributes<FixtureItemElement>, "value" \| "disabled" \| "onReady"> \{$/m);
    });

    it("has one line per @property, typed from the element and named as the element names it", () => {
        const fixture = props("Fixture");
        for (const name of ["label", "open", "variant", "items", "count", "tone", "when", "disabled"])
        {
            assert.match(fixture, new RegExp(`^    ${name}\\?: FixtureElement\\["${name}"\\];$`, "m"));
        }
        assert.match(props("FixtureItem"), /^    value\?: FixtureItemElement\["value"\];$/m);
    });

    it("leaves out readonly and non-@property fields", () => {
        assert.doesNotMatch(props("Fixture"), /\bsize\?|\binternal\?/);
    });

    it("documents props and handlers with the analyser's descriptions", () => {
        const fixture = props("Fixture");
        assert.match(fixture, /    \/\*\* Text shown in the header\. \*\/\n    label\?:/);
        assert.match(fixture, /    \/\*\* Rows to render\. \*\/\n    items\?:/);
        assert.match(fixture, /    \/\*\* whenever `open` toggles \*\/\n    onChange\?:/);
    });

    it("maps every event to an on<PascalCase> handler typed from the event", () => {
        const fixture = props("Fixture");
        assert.match(fixture, /onChange\?: \(event: Event\) => void;/);
        assert.match(fixture, /onValueChange\?: \(event: CustomEvent<\{ value: string \}>\) => void;/);
        assert.match(fixture, /onReady\?: \(event: Event\) => void;/);
    });

    it("falls back to a plain CustomEvent when the detail type isn't self-contained", () => {
        assert.match(props("Fixture"), /onTabSelect\?: \(event: CustomEvent\) => void;/);
    });

    it("adds ref and children", () => {
        assert.match(props("Fixture"), /^    ref\?: Ref<FixtureElement>;\n    children\?: ReactNode;\n}$/m);
    });

    it("merges the caller's ref, object or callback, in a setRef callback with React 19 cleanup", () => {
        const fixture = component("Fixture");
        assert.match(fixture, /const element = useRef<FixtureElement \| null>\(null\);/);
        assert.match(fixture, /const setRef = useCallback\(\(node: FixtureElement \| null\) => \{/);
        assert.match(fixture, /if \(typeof ref === "function"\) cleanup = ref\(node\);/);
        assert.match(fixture, /else if \(typeof ref === "function"\) ref\(null\);/);
        assert.match(fixture, /\}, \[ref\]\);/);
    });

    it("listens for each event in its own effect, removed on cleanup", () => {
        const fixture = component("Fixture");
        assert.match(fixture, /\{ ref, onChange, onValueChange, onTabSelect, onReady, label, withClick, items, count, when, \.\.\.props \}: FixtureProps/);
        assert.match(fixture, /node\.addEventListener\("change", onChange\);\n\s*return \(\) => node\.removeEventListener\("change", onChange\);\n\s*\}, \[onChange\]\);/);
        assert.match(fixture, /const listener = \(event: Event\) => onValueChange\(event as CustomEvent<\{ value: string \}>\);/);
        assert.match(fixture, /node\.addEventListener\("value-change", listener\);\n\s*return \(\) => node\.removeEventListener\("value-change", listener\);\n\s*\}, \[onValueChange\]\);/);
        assert.match(fixture, /node\.addEventListener\("tab-select", listener\);/);
        assert.match(fixture, /node\.addEventListener\("ready", onReady\);/);
    });

    it("assigns object props, and props without an attribute, in one effect once the element is defined", () => {
        const fixture = component("Fixture");
        assert.strictEqual(fixture.match(/whenDefined/g)?.length, 1);
        assert.match(fixture, /    useEffect\(\(\) => \{\n        const node = element\.current;\n        if \(!node\) return;\n        let current = true;\n        void customElements\.whenDefined\("fixture-el"\)\.then\(\(\) => \{\n            if \(!current\) return;\n            if \(items !== undefined\) node\.items = items;\n            if \(count !== undefined\) node\.count = count;\n            if \(when !== undefined\) node\.when = when;\n        \}\);\n        return \(\) => \{\n            current = false;\n        \};\n    \}, \[items, count, when\]\);/);
        for (const name of ["items", "count", "when"]) assert.doesNotMatch(fixture, new RegExp(`\\b${name}=\\{`));
    });

    it("routes by the resolved type: an alias of literals passes through JSX, a union with Date is assigned", () => {
        const fixture = component("Fixture");
        assert.doesNotMatch(fixture, /node\.tone/);
        assert.doesNotMatch(fixture, /\{[^}]*\btone\b[^}]*\}: FixtureProps/);
        assert.match(fixture, /node\.when = when;/);
        assert.match(props("Fixture"), /^    tone\?: FixtureElement\["tone"\];$/m);
    });

    it("passes primitives through JSX, under the attribute name when it differs from the property", () => {
        const fixture = component("Fixture");
        assert.match(fixture, /return <fixture-el label-text=\{label\} click=\{withClick\} \{\.\.\.props\} ref=\{setRef\} \/>;/);
        assert.doesNotMatch(fixture, /\b(open|variant|disabled)\b.*whenDefined/);
    });

    it("declares the tags as JSX intrinsic elements, with the props JSX can carry", () => {
        assert.match(augmentation(), /^declare module "react" \{\n    namespace JSX \{\n        interface IntrinsicElements \{\n/);
        assert.match(augmentation(), /^            "fixture-el": Omit<FixtureProps, "onChange" \| "onValueChange" \| "onTabSelect" \| "onReady" \| "label" \| "items" \| "count" \| "when" \| "withClick"> & \{ "label-text"\?: FixtureProps\["label"\]; "click"\?: FixtureProps\["withClick"\] \};$/m);
        // the rollup renames the element import outside this block only
        assert.doesNotMatch(augmentation(), /Element\b/);
        assert.match(augmentation(), /^            "fixture-item": Omit<FixtureItemProps, "onReady">;$/m);
        assert.strictEqual(code.match(/declare module/g).length, 1);
    });
});

describe("generateReact with a parent chain across packages", () => {
    const core = (className, source, events, parent = null) => ({
        className, source, properties: [], methods: [], states: [],
        events: events.map(name => ({ name, kind: "Event" })),
        html: { slots: [], parts: [] }, css: { variables: [] }, extends: parent,
    });

    const engine = core("CustomElement", { package: "@papit/web-component", file: "src/component.ts" }, ["first-render"], { builtin: "HTMLElement" });
    const base = core("Base", { package: "@tmp/base", file: "src/component.ts" }, ["base-change"], engine);
    const element = { ...core("Tabs", { file: "src/component.ts" }, ["change"], base), tagName: "pap-tabs" };
    const code = generateReact({ name: "@tmp/tabs", version: "1.0.0", elements: [element] });

    it("keeps events from the package and from non-engine parents", () => {
        assert.match(code, /onChange\?: \(event: Event\) => void;/);
        assert.match(code, /onBaseChange\?: \(event: Event\) => void;/);
    });

    it("skips events inherited from @papit/web-component", () => {
        assert.doesNotMatch(code, /onFirstRender|"first-render"/);
    });

    it("declares the tag as an intrinsic element with the plain props when nothing is left out but handlers", () => {
        assert.match(code, /"pap-tabs": Omit<TabsProps, "onChange" \| "onBaseChange">;/);
    });
});

describe("generateReact with nothing to leave out of the intrinsic element", () => {
    const element = {
        tagName: "pap-plain", className: "Plain", source: { file: "src/component.ts" },
        properties: [{ name: "label", type: "string", attribute: "label" }],
        methods: [], events: [], states: [], html: { slots: [], parts: [] }, css: { variables: [] }, extends: { builtin: "HTMLElement" },
    };
    const code = generateReact({ name: "@tmp/plain", version: "1.0.0", elements: [element] });

    it("uses the props interface as is", () => {
        assert.match(code, /^            "pap-plain": PlainProps;$/m);
    });

    it("only imports what it uses from react", () => {
        assert.match(code, /^import \{ useCallback, useRef \} from "react";$/m);
    });
});

describe("generateReact routing by type", () => {
    const element = (properties) => ({
        tagName: "pap-route", className: "Route", source: { file: "src/component.ts" },
        properties: properties.map(p => ({ attribute: p.name.toLowerCase(), ...p })),
        methods: [], events: [], states: [], html: { slots: [], parts: [] }, css: { variables: [] }, extends: { builtin: "HTMLElement" },
    });
    const code = generateReact({ name: "@tmp/route", version: "1.0.0", elements: [element([
        { name: "color", type: "Color", resolvedType: "\"primary\" | \"secondary\"" },
        { name: "mode", type: "Group[\"mode\"]", resolvedType: "\"a\" | \"b\" | undefined" },
        { name: "flag", type: "Flag", resolvedType: "boolean | 1 | -2.5 | null" },
        { name: "state", type: "State", resolvedType: "{ valid?: string[] | undefined; }" },
        { name: "unresolved", type: "Unknown" },
        { name: "plain", type: "string | number" },
    ])] });

    it("passes a resolved union of literals and primitives through JSX", () => {
        assert.match(code, /^export function Route\(\{ ref, state, unresolved, \.\.\.props \}: RouteProps\)/m);
    });

    it("assigns a resolved object, and falls back to the written type without a resolved one", () => {
        assert.match(code, /if \(state !== undefined\) node\.state = state;\n\s*if \(unresolved !== undefined\) node\.unresolved = unresolved;/);
        assert.match(code, /\}, \[state, unresolved\]\);/);
    });

    it("keeps the element's own property type in the props interface", () => {
        assert.match(code, /^    color\?: RouteElement\["color"\];$/m);
        assert.match(code, /^    mode\?: RouteElement\["mode"\];$/m);
    });
});
