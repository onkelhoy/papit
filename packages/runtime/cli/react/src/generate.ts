import type { Core, Event, PackageAnalysis, Property } from "@papit/analyse";

export const MARKER = "// generated by @papit/react";

// events the engine dispatches on every element are not part of a component's API
const ENGINE = "@papit/web-component";

type Listener = { event: string; handler: string; type: string; description?: string };
/**
 * How a prop reaches the element: `pass` through JSX as is, `attribute` through JSX under its
 * attribute name, `assign` as a property once the element is defined.
 */
type Prop = { name: string; description?: string; via: "pass" | "attribute" | "assign"; attribute?: string };
type Wrapper = { name: string; tagName: string; element: string; props: Prop[]; listeners: Listener[] };

// type names a CustomEvent detail may use and still compile in the generated file
const GLOBAL_TYPES = new Set([
    "string", "number", "boolean", "bigint", "symbol", "object", "null", "undefined", "void", "unknown", "any", "never",
    "true", "false", "readonly", "keyof",
    "Array", "ReadonlyArray", "Record", "Partial", "Required", "Readonly", "Pick", "Omit", "Map", "Set", "Date", "Promise",
    "Element", "HTMLElement", "Node", "Event", "File", "FileList", "Blob",
]);

/** The class and its analysed parents, nearest first. Stops at a built-in or an unresolved reference. */
function chain(core: Core) {
    const list: Core[] = [];
    let current: Core["extends"] = core;
    while (current && "properties" in current)
    {
        list.push(current);
        current = current.extends;
    }
    return list;
}

function unique<T extends { name: string }>(items: T[]) {
    const seen = new Set<string>();
    return items.filter(item => !seen.has(item.name) && seen.add(item.name));
}

/** `tab-select` → `onTabSelect`. */
function handlerName(event: string) {
    return "on" + event
        .split(/[^A-Za-z0-9]+/)
        .filter(Boolean)
        .map(part => part[0]!.toUpperCase() + part.slice(1))
        .join("");
}

/** A detail type is kept only when every name in it is a key or a global type, as nothing else is imported. */
function selfContained(detail: string) {
    const code = detail.replace(/(["'`])(?:\\.|(?!\1)[^\\])*\1/g, "\"\"");
    for (const match of code.matchAll(/[A-Za-z_$][\w$]*/g))
    {
        const after = code.slice(match.index! + match[0].length);
        if (/^\s*\??\s*:/.test(after)) continue; // a property key
        if (!GLOBAL_TYPES.has(match[0])) return false;
    }
    return true;
}

function eventType(event: Event) {
    if (event.kind !== "CustomEvent") return "Event";
    return event.detail && selfContained(event.detail) ? `CustomEvent<${event.detail}>` : "CustomEvent";
}

/** `a | (b | "c")` → `["a", "b", "\"c\""]`: the members of a union, split at the top level only. */
function unionParts(type: string): string[] {
    const parts: string[] = [];
    let depth = 0;
    let quote = "";
    let start = 0;
    for (let i = 0; i < type.length; i++)
    {
        const char = type[i]!;
        if (quote)
        {
            if (char === "\\") i++;
            else if (char === quote) quote = "";
        }
        else if (char === "\"" || char === "'" || char === "`") quote = char;
        else if ("([{<".includes(char)) depth++;
        else if (")]}>".includes(char)) depth--;
        else if (char === "|" && depth === 0)
        {
            parts.push(type.slice(start, i));
            start = i + 1;
        }
    }
    parts.push(type.slice(start));

    return parts
        .map(part => part.trim())
        .filter(Boolean)
        .flatMap(part => /^\(.*\)$/s.test(part) ? unionParts(part.slice(1, -1)) : [part]);
}

const PRIMITIVE = /^(?:string|number|boolean|null|undefined|true|false|-?\d+(?:\.\d+)?|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|string\s*&\s*\{\s*\})$/;

/**
 * Whether a type is a string, number, boolean or a union of those and literals.
 * Conservative: anything else counts as an object, an alias the analyser couldn't resolve included.
 */
function primitive(type: string) {
    const parts = unionParts(type);
    return parts.length > 0 && parts.every(part => PRIMITIVE.test(part));
}

function prop(property: Property): Prop {
    const { name, description } = property;
    // the analyser's resolved type sees through aliases and indexed access types
    if (typeof property.attribute !== "string" || !primitive(property.resolvedType ?? property.type)) return { name, description, via: "assign" };

    // HTML lowercases attribute names, so `defaultValue` still reaches `defaultvalue`
    if (property.attribute === name.toLowerCase()) return { name, description, via: "pass" };
    return { name, description, via: "attribute", attribute: property.attribute };
}

function wrapper(core: Core): Wrapper {
    const classes = chain(core);
    const props = unique(classes.flatMap(c => c.properties))
        .filter((property: Property) => property.attribute !== undefined && !property.readonly)
        .map(prop);
    const listeners = unique(classes.filter(c => c.source.package !== ENGINE).flatMap(c => c.events))
        .map(event => ({ event: event.name, handler: handlerName(event.name), type: eventType(event), description: event.description }));

    return { name: core.className, tagName: core.tagName!, element: `${core.className}Element`, props, listeners };
}

const union = (names: string[]) => names.map(name => JSON.stringify(name)).join(" | ");

/** A JSDoc block for `text` at `indent`, nothing without text. */
function doc(text: string | undefined, indent: string) {
    const lines = text?.trim().replace(/\*\//g, "*\\/").split(/\r?\n/) ?? [];
    if (!lines[0]) return [];
    if (lines.length === 1) return [`${indent}/** ${lines[0]} */`];
    return [`${indent}/**`, ...lines.map(line => `${indent} * ${line}`.trimEnd()), `${indent} */`];
}

function propsInterface({ name, element, props, listeners }: Wrapper) {
    const clashing = [...props.map(p => p.name), ...listeners.map(l => l.handler)];
    const base = clashing.length ? `Omit<HTMLAttributes<${element}>, ${union(clashing)}>` : `HTMLAttributes<${element}>`;

    return [
        `export interface ${name}Props extends ${base} {`,
        ...props.flatMap(p => [...doc(p.description, "    "), `    ${p.name}?: ${element}[${JSON.stringify(p.name)}];`]),
        ...listeners.flatMap(l => [...doc(l.description, "    "), `    ${l.handler}?: (event: ${l.type}) => void;`]),
        `    ref?: Ref<${element}>;`,
        `    children?: ReactNode;`,
        `}`,
    ];
}

function listenerEffect({ event, handler, type }: Listener) {
    // a handler typed with a CustomEvent isn't an EventListener, so it's wrapped
    const listener = type === "Event" ? handler : "listener";
    return [
        `    useEffect(() => {`,
        `        const node = element.current;`,
        `        if (!node || !${handler}) return;`,
        ...listener === handler ? [] : [`        const listener = (event: Event) => ${handler}(event as ${type});`],
        `        node.addEventListener(${JSON.stringify(event)}, ${listener});`,
        `        return () => node.removeEventListener(${JSON.stringify(event)}, ${listener});`,
        `    }, [${handler}]);`,
    ];
}

/** One effect for all assigned props: assigning in a single `whenDefined` keeps the order and the waits to one. */
function assignEffect(tagName: string, assigned: Prop[]) {
    const names = assigned.map(p => p.name);
    return [
        `    // objects, and props without an attribute, are set once <${tagName}> is defined:`,
        `    // as JSX props, React would first write them as attributes the element doesn't read`,
        `    useEffect(() => {`,
        `        const node = element.current;`,
        `        if (!node) return;`,
        `        let current = true;`,
        `        void customElements.whenDefined(${JSON.stringify(tagName)}).then(() => {`,
        `            if (!current) return;`,
        ...names.map(name => `            if (${name} !== undefined) node.${name} = ${name};`),
        `        });`,
        `        return () => {`,
        `            current = false;`,
        `        };`,
        `    }, [${names.join(", ")}]);`,
    ];
}

function component(wrapper: Wrapper) {
    const { name, tagName, element, props, listeners } = wrapper;
    const renamed = props.filter(p => p.via === "attribute");
    const assigned = props.filter(p => p.via === "assign");
    const destructured = ["ref", ...listeners.map(l => l.handler), ...renamed.map(p => p.name), ...assigned.map(p => p.name), "...props"];
    const attributes = renamed.map(p => `${p.attribute}={${p.name}} `).join("");

    return [
        ...propsInterface(wrapper),
        ``,
        `/** React wrapper for the \`${tagName}\` element. */`,
        `export function ${name}({ ${destructured.join(", ")} }: ${name}Props): ReactElement {`,
        `    const element = useRef<${element} | null>(null);`,
        ``,
        `    const setRef = useCallback((node: ${element} | null) => {`,
        `        element.current = node;`,
        `        let cleanup: void | (() => void) = undefined;`,
        `        if (typeof ref === "function") cleanup = ref(node);`,
        `        else if (ref) ref.current = node;`,
        ``,
        `        return () => {`,
        `            element.current = null;`,
        `            if (typeof cleanup === "function") cleanup();`,
        `            else if (typeof ref === "function") ref(null);`,
        `            else if (ref) ref.current = null;`,
        `        };`,
        `    }, [ref]);`,
        ...listeners.flatMap(listener => [``, ...listenerEffect(listener)]),
        ...assigned.length ? [``, ...assignEffect(tagName, assigned)] : [],
        ``,
        `    return <${tagName} ${attributes}{...props} ref={setRef} />;`,
        `}`,
    ].join("\n");
}

/**
 * What the raw tag takes in JSX: the props, less the handlers and those the component doesn't pass as they are,
 * plus each renamed prop under its attribute name, typed from the props interface: the rollup renames
 * the element import everywhere but in this block, which bundle-ts copies as it is.
 */
function intrinsic({ name, tagName, props, listeners }: Wrapper) {
    const omitted = [...listeners.map(l => l.handler), ...props.filter(p => p.via !== "pass").map(p => p.name)];
    const base = omitted.length ? `Omit<${name}Props, ${union(omitted)}>` : `${name}Props`;
    const renamed = props
        .filter(p => p.via === "attribute")
        .map(p => `${JSON.stringify(p.attribute)}?: ${name}Props[${JSON.stringify(p.name)}]`);
    return `            ${JSON.stringify(tagName)}: ${renamed.length ? `${base} & { ${renamed.join("; ")} }` : base};`;
}

/**
 * The source of `src/react-wrapper.tsx` for a package: one React 19 function component per custom element,
 * named after its class, and each tag declared as a JSX intrinsic element.
 * Props are the element's `@property` fields (inherited included, readonly left out), typed from the class itself.
 * Strings, numbers, booleans and literal unions (aliases resolved by the analyser) go through JSX; objects and
 * props without an attribute are assigned in one effect once the element is defined. Every event becomes an `on<PascalCase>` prop listened for on the element,
 * except those inherited from `@papit/web-component`.
 * The package is imported by its own name, and in the browser only, so server rendering never loads it.
 */
export function generateReact(analysis: PackageAnalysis): string {
    const wrappers = analysis.elements.filter(element => element.tagName).map(wrapper);
    const types = wrappers.map(w => `${w.name} as ${w.element}`).join(", ");
    const effects = wrappers.some(w => w.listeners.length || w.props.some(p => p.via === "assign"));
    const hooks = ["useCallback", ...effects ? ["useEffect"] : [], "useRef"];

    return [
        `"use client";`,
        MARKER,
        `// Regenerate with \`npx @papit/react\`. Delete the line above to take this file over by hand.`,
        `import { ${hooks.join(", ")} } from "react";`,
        `import type { HTMLAttributes, ReactElement, ReactNode, Ref } from "react";`,
        `import type { ${types} } from ${JSON.stringify(analysis.name)};`,
        ``,
        `// the package defines its elements on import and needs the DOM, so it only loads in the browser`,
        `if (typeof window !== "undefined")`,
        `{`,
        `    void import(${JSON.stringify(analysis.name)});`,
        `}`,
        ``,
        wrappers.map(component).join("\n\n"),
        ``,
        `declare module "react" {`,
        `    namespace JSX {`,
        `        interface IntrinsicElements {`,
        ...wrappers.map(intrinsic),
        `        }`,
        `    }`,
        `}`,
        ``,
    ].join("\n");
}
